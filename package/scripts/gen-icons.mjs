// Generates the per-family icon modules in the package folder: one named export per icon (camelCase) + default export.
// Reads data/lucide-nodes.json and data/families/*.json. Usage: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const PKG = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(PKG, 'data');
const RESERVED = new Set('break case catch class const continue debugger default delete do else enum export extends false finally for function if import in instanceof new null return super switch this throw true try typeof var void while with yield let static implements interface package private protected public await async of undefined NaN Infinity arguments eval'.split(' '));

function camel(name) {
  const parts = name.split(/[^A-Za-z0-9]+/).filter(Boolean);
  let s = parts.map((p, i) => (i === 0 ? p.toLowerCase() : p[0].toUpperCase() + p.slice(1).toLowerCase())).join('');
  if (!s) s = 'icon';
  if (/^[0-9]/.test(s) || RESERVED.has(s)) s = '_' + s;
  return s;
}

function moduleText(header, meta, icons, itype, dts) {
  const used = new Set();
  const lines = [header];
  const pairs = [];
  for (const name of Object.keys(icons)) {
    let id = camel(name);
    let n = 2;
    while (used.has(id)) id = camel(name) + '_' + n++;
    used.add(id);
    pairs.push([name, id]);
    dts.push('export const ' + id + ': ' + itype + ';');
    lines.push('export const ' + id + ' = ' + JSON.stringify(icons[name]) + ';');
  }
  const map = pairs.map(([n, id]) => JSON.stringify(n) + ': ' + id).join(', ');
  if (meta) dts.push('declare const $spec: FamilySpec;\nexport default $spec;');
  else dts.push('declare const $map: Record<string, IconNode>;\nexport default $map;');
  if (meta) lines.push('export default { ' + Object.entries(meta).map(([k, v]) => k + ': ' + JSON.stringify(v)).join(', ') + ', icons: { ' + map + ' } };');
  else lines.push('export default { ' + map + ' };');
  return { text: lines.join('\n') + '\n', count: pairs.length };
}

const report = [];
// Lucide: from data/lucide-nodes.json.
{
  const mod = { default: JSON.parse(readFileSync(join(DATA, 'lucide-nodes.json'), 'utf8')) };
  const header = '// Generated by scripts/gen-icons.mjs from data/lucide-nodes.json (lucide-static 1.50.0). Do not edit.\n// Lucide icons: ISC License, Copyright (c) Lucide Contributors.\n// One named export per icon (camelCase). The default export is the whole map keyed by the original names.';
  const dts = ["import type { IconNode } from './index.js';"];
  const { text, count } = moduleText(header, null, mod.default, 'IconNode', dts);
  writeFileSync(join(PKG, 'lucide.js'), text);
  writeFileSync(join(PKG, 'lucide.d.ts'), '// Generated by scripts/gen-icons.mjs. Do not edit.\n' + dts.join('\n') + '\n');
  report.push(['lucide', count, statSync(join(PKG, 'lucide.js')).size]);
}

const FAMS = ['tabler-outline', 'tabler-filled', 'hugeicons', 'phosphor-thin-s', 'phosphor-light-s', 'phosphor-regular-s', 'phosphor-bold-s', 'phosphor-fill', 'phosphor-duotone-s', 'remix-line-s', 'remix-fill'];
const metas = { lucide: { id: 'lucide', kind: 'stroke', viewBox: '0 0 24 24', strokeWidth: 2, linecap: 'round', linejoin: 'round' } };
for (const id of FAMS) {
  const fam = JSON.parse(readFileSync(join(DATA, 'families', id + '.json'), 'utf8'));
  const { icons, ...head } = fam;
  delete head.fallbackCount;
  delete head.source;
  delete head.nativeStrokeWidth;
  const header = '// Generated by scripts/gen-icons.mjs from data/families/' + id + '.json. Do not edit.\n// One named export per icon (camelCase). The default export is the family spec ({ id, kind, viewBox, strokeWidth, icons }), keyed by the original names.\n// Use registerFamilyIcons(\'' + id + '\', { name: namedExport }) to register only the icons you import.';
  const rec = id.endsWith('-s');
  const dts = ["import type { IconNode, FamilySpec" + (rec ? ', FamilyIconRecord' : '') + " } from './index.js';"];
  const { text, count } = moduleText(header, head, icons, rec ? 'FamilyIconRecord' : 'IconNode', dts);
  writeFileSync(join(PKG, id + '.js'), text);
  writeFileSync(join(PKG, id + '.d.ts'), '// Generated by scripts/gen-icons.mjs. Do not edit.\n' + dts.join('\n') + '\n');
  metas[id] = { id: head.id, kind: head.kind, viewBox: head.viewBox, strokeWidth: head.strokeWidth, linecap: head.linecap || 'round', linejoin: head.linejoin || 'round' };
  report.push([id, count, statSync(join(PKG, id + '.js')).size]);
}
delete metas.lucide;
writeFileSync(join(PKG, 'families-meta.js'), '// Generated by scripts/gen-icons.mjs. The settings of each family module. Used by registerFamilyIcons.\nexport const FAMILY_META = ' + JSON.stringify(metas, null, 1) + ';\n');
console.table(report.map(([id, n, b]) => ({ id, icons: n, kB: Math.round(b / 1024) })));
